function skippedNote({
  duplicates,
  unsupported,
}: {
  duplicates: number;
  unsupported: number;
}): string {
  const notes = [
    duplicates > 0 ? `${number(duplicates)} تکراری نادیده گرفته شد` : '',
    unsupported > 0
      ? `${number(unsupported)} پشتیبانی‌نشده نادیده گرفته شد`
      : '',
  ].filter(Boolean);
  return notes.length ? ` (${notes.join('، ')})` : '';
}
